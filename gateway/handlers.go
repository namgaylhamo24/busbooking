package main

import (
	"context"
	"net/http"
	"time"

	routepb "busbooking/gen/routepb"
	ticketpb "busbooking/gen/ticketpb"
)

// Handler holds the gRPC clients used by the REST handlers.
type Handler struct {
	routes  routepb.RouteServiceClient
	tickets ticketpb.TicketServiceClient
	timeout time.Duration
}

// Register wires the resource-based REST URLs to their handlers.
func (h *Handler) Register(mux *http.ServeMux) {
	mux.HandleFunc("GET /health", h.health)

	mux.HandleFunc("POST /routes", h.createRoute)
	mux.HandleFunc("GET /routes", h.listRoutes)
	mux.HandleFunc("GET /routes/{id}", h.getRoute)
	mux.HandleFunc("PUT /routes/{id}", h.updateRoute)
	mux.HandleFunc("DELETE /routes/{id}", h.deleteRoute)

	mux.HandleFunc("POST /tickets", h.createTicket)
	mux.HandleFunc("GET /tickets", h.listTickets)
	mux.HandleFunc("GET /tickets/{id}", h.getTicket)
	mux.HandleFunc("PUT /tickets/{id}", h.updateTicket)
	mux.HandleFunc("DELETE /tickets/{id}", h.deleteTicket)

	// Anything else gets a JSON 404 instead of Go's default plain text.
	mux.HandleFunc("/", func(w http.ResponseWriter, r *http.Request) {
		writeError(w, http.StatusNotFound, "no such endpoint: "+r.Method+" "+r.URL.Path)
	})
}

// ctx gives every backend call a deadline so a request can never hang.
func (h *Handler) ctx(r *http.Request) (context.Context, context.CancelFunc) {
	return context.WithTimeout(r.Context(), h.timeout)
}

func (h *Handler) health(w http.ResponseWriter, r *http.Request) {
	writeRaw(w, http.StatusOK, map[string]string{"status": "ok"})
}

// ---------------------------------------------------------------- routes

func (h *Handler) createRoute(w http.ResponseWriter, r *http.Request) {
	route := &routepb.Route{}
	if !decodeBody(w, r, route) {
		return
	}
	route.Id = "" // ids are always generated by the service

	ctx, cancel := h.ctx(r)
	defer cancel()
	created, err := h.routes.CreateRoute(ctx, &routepb.CreateRouteRequest{Route: route})
	if err != nil {
		writeGRPCError(w, err)
		return
	}
	w.Header().Set("Location", "/routes/"+created.Id)
	writeProto(w, http.StatusCreated, created)
}

func (h *Handler) listRoutes(w http.ResponseWriter, r *http.Request) {
	ctx, cancel := h.ctx(r)
	defer cancel()
	resp, err := h.routes.ListRoutes(ctx, &routepb.ListRoutesRequest{})
	if err != nil {
		writeGRPCError(w, err)
		return
	}
	writeProto(w, http.StatusOK, resp)
}

func (h *Handler) getRoute(w http.ResponseWriter, r *http.Request) {
	ctx, cancel := h.ctx(r)
	defer cancel()
	route, err := h.routes.GetRoute(ctx, &routepb.GetRouteRequest{Id: r.PathValue("id")})
	if err != nil {
		writeGRPCError(w, err)
		return
	}
	writeProto(w, http.StatusOK, route)
}

func (h *Handler) updateRoute(w http.ResponseWriter, r *http.Request) {
	route := &routepb.Route{}
	if !decodeBody(w, r, route) {
		return
	}
	id := r.PathValue("id")
	if route.Id != "" && route.Id != id {
		writeError(w, http.StatusBadRequest, "id in body does not match id in URL")
		return
	}
	route.Id = id

	ctx, cancel := h.ctx(r)
	defer cancel()
	updated, err := h.routes.UpdateRoute(ctx, &routepb.UpdateRouteRequest{Route: route})
	if err != nil {
		writeGRPCError(w, err)
		return
	}
	writeProto(w, http.StatusOK, updated)
}

func (h *Handler) deleteRoute(w http.ResponseWriter, r *http.Request) {
	ctx, cancel := h.ctx(r)
	defer cancel()
	if _, err := h.routes.DeleteRoute(ctx, &routepb.DeleteRouteRequest{Id: r.PathValue("id")}); err != nil {
		writeGRPCError(w, err)
		return
	}
	w.WriteHeader(http.StatusNoContent)
}

